const ACCENTS: Record<string, string> = { Á: 'A', É: 'E', Í: 'I', Ó: 'O', Ú: 'U', Ü: 'U' };

function glyph(ch: string): number[] {
  const up = ch.toUpperCase();
  return FONT[up] ?? FONT[ACCENTS[up]] ?? FONT['?'];
}

export function drawText(
  g: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  opts: { scale?: number; shadow?: string; spacing?: number } = {},
): number {
  const s = opts.scale ?? 1;
  const adv = (opts.spacing ?? 8) * s;
  const draw = (ox: number, oy: number, col: string) => {
    g.fillStyle = col;
    let cx = x + ox;
    for (const ch of text) {
      const gl = glyph(ch);
      for (let r = 0; r < 7; r++) {
        const bits = gl[r];
        if (!bits) continue;
        for (let c = 0; c < 5; c++) {
          if (bits & (0x10 >> c)) g.fillRect(cx + c * s, y + oy + r * s, s, s);
        }
      }
      cx += adv;
    }
  };
  if (opts.shadow) draw(s, s, opts.shadow);
  draw(0, 0, color);
  return text.length * adv;
}

export function textWidth(text: string, scale = 1, spacing = 8) {
  return text.length * spacing * scale;
}

export function drawTextCentered(
  g: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color: string,
  opts: { scale?: number; shadow?: string; spacing?: number } = {},
) {
  const s = opts.scale ?? 1;
  const sp = opts.spacing ?? 8;
  // glyphs are 5 wide inside the advance, so center on (len*sp - (sp-5))
  const w = text.length * sp * s - (sp - 5) * s;
  drawText(g, text, Math.round(cx - w / 2), y, color, opts);
}

// Renders text as chunky carved stone letters (used for the logo)
export function makeStoneText(text: string, scale: number, palette?: { fill: string; hi: string; lo: string; outline: string }): HTMLCanvasElement {
  const p = palette ?? { fill: PAL.grey, hi: PAL.white, lo: PAL.dgrey, outline: PAL.black };
  const spacing = 6;
  const w = text.length * spacing * scale + 2;
  const h = 7 * scale + 2;
  const grid: Uint8Array = new Uint8Array(w * h);
  let cx = 1;
  for (const ch of text) {
    const gl = glyph(ch);
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        if (gl[r] & (0x10 >> c)) {
          for (let yy = 0; yy < scale; yy++) for (let xx = 0; xx < scale; xx++) grid[(1 + r * scale + yy) * w + cx + c * scale + xx] = 1;
        }
      }
    }
    cx += spacing * scale;
  }
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const g = canvas.getContext('2d')!;
  const at = (x: number, y: number) => (x < 0 || y < 0 || x >= w || y >= h ? 0 : grid[y * w + x]);
  let seed = 7;
  const rnd = () => {
    seed = (seed * 1103515245 + 12345) & 0x7fffffff;
    return seed / 0x7fffffff;
  };
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (grid[y * w + x]) {
        let col = p.fill;
        if (!at(x, y - 1)) col = p.hi;
        else if (!at(x, y + 1)) col = p.lo;
        else if (!at(x - 1, y)) col = p.hi;
        else if (!at(x + 1, y)) col = p.lo;
        else if (rnd() < 0.08) col = p.lo;
        g.fillStyle = col;
        g.fillRect(x, y, 1, 1);
      } else if (at(x - 1, y) || at(x + 1, y) || at(x, y - 1) || at(x, y + 1)) {
        g.fillStyle = p.outline;
        g.fillRect(x, y, 1, 1);
      }
    }
  }
  return canvas;
}
